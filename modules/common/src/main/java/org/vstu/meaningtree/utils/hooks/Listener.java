package org.vstu.meaningtree.utils.hooks;

/**
 * Наблюдатель: узнаёт о происходящем, но не влияет на результат.
 * <p>
 * В отличие от {@link Interceptor}, порядок наблюдателей между собой не значим, и
 * наблюдатель не может сломать трансляцию. Все наблюдатели фазы вызываются <b>после</b>
 * всех перехватчиков и видят уже итоговое значение.
 * <p>
 * Типичные применения: сбор метрик, индексация соответствий «исходный код ↔ узел»,
 * трассировка трансляции при отладке.
 *
 * @param <S> тип субъекта фазы
 * @param <V> тип значения фазы
 */
@FunctionalInterface
public interface Listener<S, V> {
    void observe(S subject, V value, HookContext context);
}

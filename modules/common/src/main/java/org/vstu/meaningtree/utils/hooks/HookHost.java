package org.vstu.meaningtree.utils.hooks;

import org.vstu.meaningtree.utils.scopes.ScopeTable;

/**
 * Владелец реестра хуков — компонент трансляции, в котором срабатывают фазы.
 * <p>
 * Интерфейс намеренно узкий: он существует затем, чтобы пакет {@code utils.hooks} не
 * зависел от пакета {@code languages} и не образовывал с ним цикл. Всё, что подсистеме
 * хуков нужно знать о владельце — как называется его язык и какая у него сейчас таблица
 * областей видимости.
 * <p>
 * Хук, которому нужен доступ к чему-то более специфичному (конфигурации, токенизатору,
 * самому viewer'у), получает это через замыкание в месте регистрации, а не через это
 * окружение.
 */
public interface HookHost {

    /**
     * Таблица областей видимости текущей трансляции. Пересоздаётся между прогонами.
     */
    ScopeTable hookScope();

    /**
     * Имя языка владельца — для диагностических сообщений.
     */
    String hookLanguageName();
}

package org.vstu.meaningtree.utils.hooks;

/**
 * Перехватчик: участвует в конвейере трансляции и возвращает значение, которое пойдёт
 * дальше.
 * <p>
 * Контракт, отличающий его от {@link Listener}:
 * <ul>
 *     <li>обязан быть <b>тотальным</b> — если делать нечего, надо вернуть входное значение,
 *     а не {@code null};</li>
 *     <li>порядок применения <b>значим</b>: перехватчики композируются, результат каждого
 *     становится входом следующего (см. {@link HookOrder});</li>
 *     <li>может сломать трансляцию, поэтому регистрировать его следует осознанно.</li>
 * </ul>
 *
 * @param <S> тип субъекта фазы
 * @param <V> тип значения, текущего по конвейеру
 */
@FunctionalInterface
public interface Interceptor<S, V> {
    V intercept(S subject, V value, HookContext context);
}

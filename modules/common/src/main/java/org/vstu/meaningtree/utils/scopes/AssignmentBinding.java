package org.vstu.meaningtree.utils.scopes;

/**
 * Правило языка о том, какую переменную связывает присваивание имени, которое в текущей
 * области ещё не объявлено.
 * <p>
 * Это семантика языка, а не свойство дерева, поэтому передаётся снаружи так же, как
 * {@link ScopePolicy}: по форме узла «присваивание идентификатору» два случая неразличимы.
 */
public enum AssignmentBinding {
    /**
     * Присваивание связывает ближайшую видимую одноимённую переменную и создаёт новую, только
     * если такой нет. Так устроены Java и C++: неизвестному имени присвоить нельзя вовсе, а
     * известное — это всегда та переменная, которую видно.
     */
    ENCLOSING,

    /**
     * Присваивание связывает переменную текущей области, даже когда одноимённая видна снаружи;
     * внешнюю оно затеняет, а не меняет. Так устроен Python: чтобы писать во внешнее имя, его
     * надо объявить {@code global} или {@code nonlocal} — только тогда цель ищется снаружи.
     */
    LOCAL
}

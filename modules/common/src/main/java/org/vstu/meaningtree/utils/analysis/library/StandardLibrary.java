package org.vstu.meaningtree.utils.analysis.library;

import org.jetbrains.annotations.NotNull;

import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * Стандартная библиотека языка: что известно про имена, которые язык предоставляет сам.
 * <p>
 * Правило языка, а не работа: описание неизменяемо, ничего не вычисляет и не ходит наружу,
 * поэтому живёт в {@code LanguageBehavior} наравне с границами областей видимости и правилами
 * преобразования типов.
 * <p>
 * Абстракция общая, потому что общий и вопрос. Единица подключения под имя нужна C++
 * ({@code strcpy} требует {@code <cstring>}), импорт под имя — Python и Java; типы параметров
 * нужны выводу типов, анализу преобразований и разрешению перегрузок независимо от языка.
 * Языкоспецифично здесь только содержимое таблицы, и оно живёт в модуле своего языка.
 * <p>
 * Единый источник: всё, что известно про имя, — одна запись {@link LibrarySymbol}. Отдельных
 * таблиц «имя → заголовок», «имя → сигнатура» и «заголовок → состав» не бывает, иначе они
 * разъезжаются.
 *
 * <h2>Неизвестное и неполное</h2>
 * Имена, о которых реализация не знает, — норма, а не ошибка: библиотека любого языка больше,
 * чем любая практически полезная таблица, и пустой ответ означает «неизвестно», а не «такого
 * имени нет». Именно поэтому по таблице нельзя судить, что единица подключения не нужна:
 * пропущенное имя выглядело бы как отсутствие обращений. Для этого вопроса существует
 * {@link #completeUnits()} — явный список единиц, состав которых описан полностью, и только про
 * них {@link #namesOf(String)} отвечает по существу.
 */
public interface StandardLibrary {

    /**
     * Всё, что известно про имя.
     *
     * @return пусто, если имя реализации неизвестно
     */
    Optional<LibrarySymbol> symbol(@NotNull String name);

    /**
     * Единицы подключения, состав которых описан полностью: перечислены все имена, которые они
     * дают. Только про такую единицу можно утверждать, что в коде нет ни одного её имени.
     */
    Set<String> completeUnits();

    /**
     * Полный состав единицы подключения.
     *
     * @return пусто, если состав неизвестен — единица не объявлена полной
     *         (см. {@link #completeUnits()})
     */
    Optional<Set<String>> namesOf(@NotNull String unit);

    /**
     * Сигнатура функции по имени, под которым она вызывается в коде.
     *
     * @return пусто, если имя неизвестно, принадлежит не функции или её сигнатура не описана
     */
    default Optional<LibraryFunction> function(@NotNull String name) {
        return symbol(name).map(LibrarySymbol::signature);
    }

    /**
     * Единица подключения, без которой имя не соберётся.
     *
     * @return пусто, если имя неизвестно или подключать нечего — оно встроено в язык
     */
    default Optional<String> unitFor(@NotNull String name) {
        return symbol(name).flatMap(LibrarySymbol::canonicalUnit);
    }

    /**
     * Библиотека, про которую ничего не известно, — умолчание для языка, чья таблица ещё не
     * описана. Отдельного «нет библиотеки» не бывает: у любого языка она есть, вопрос лишь в
     * том, описана ли она здесь.
     */
    static StandardLibrary unknown() {
        return new IndexedStandardLibrary(List.of(), Set.of());
    }
}

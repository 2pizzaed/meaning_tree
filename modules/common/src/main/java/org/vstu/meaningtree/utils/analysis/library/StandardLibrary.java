package org.vstu.meaningtree.utils.analysis.library;

import org.jetbrains.annotations.NotNull;

import java.util.Optional;

/**
 * Стандартная библиотека языка: что известно про функции, которые язык предоставляет сам.
 * <p>
 * Правило языка, а не работа: описание неизменяемо, ничего не вычисляет и не ходит наружу,
 * поэтому живёт в {@code LanguageBehavior} наравне с границами областей видимости и правилами
 * преобразования типов.
 * <p>
 * Абстракция общая, потому что общий и вопрос. Заголовок под вызов нужен C++ ({@code strcpy}
 * требует {@code <cstring>}), импорт под вызов — Python и Java; типы параметров нужны выводу
 * типов, анализу преобразований и разрешению перегрузок независимо от языка. Языкоспецифично
 * здесь только содержимое таблицы, и оно живёт в модуле своего языка.
 * <p>
 * Функции, о которых реализация не знает, — норма, а не ошибка: библиотека любого языка больше,
 * чем любая практически полезная таблица, и пустой ответ означает «неизвестно», а не «такой
 * функции нет».
 */
@FunctionalInterface
public interface StandardLibrary {

    /**
     * Описание функции по имени, под которым она вызывается в коде.
     *
     * @return пусто, если функция реализации неизвестна
     */
    Optional<LibraryFunction> function(@NotNull String functionName);

    /**
     * Единица подключения, без которой вызов не соберётся.
     *
     * @return пусто, если функция неизвестна или подключать нечего
     */
    default Optional<String> headerForFunction(@NotNull String functionName) {
        return function(functionName).map(LibraryFunction::header);
    }

    /**
     * Библиотека, про которую ничего не известно, — умолчание для языка, чья таблица ещё не
     * описана. Отдельного «нет библиотеки» не бывает: у любого языка она есть, вопрос лишь в
     * том, описана ли она здесь.
     */
    static StandardLibrary unknown() {
        return functionName -> Optional.empty();
    }
}
